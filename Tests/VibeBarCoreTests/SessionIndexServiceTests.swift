    @discardableResult
    private func writeCodexRollout() throws -> URL {
        let ideEnvelope = """
        # Context from my IDE setup:\\nopen file: /Users/example/proj/main.swift\\n\
        ## My request for Codex:\\nRefactor the rollout parser
        """
        let lines = [
            """
            {"type":"session_meta","timestamp":"2026-02-03T13:58:51.000Z","payload":\
            {"id":"\(codexID)","cwd":"/Users/example/other"}}
            """,
            """
            {"type":"response_item","timestamp":"2026-02-03T13:58:52.000Z","payload":\
            {"type":"message","role":"user","content":[{"type":"input_text","text":"\(ideEnvelope)"}]}}
            """,
            """
            {"type":"response_item","timestamp":"2026-02-03T13:58:53.000Z","payload":\
            {"type":"function_call","name":"shell","arguments":"{}"}}
            """,
            """
