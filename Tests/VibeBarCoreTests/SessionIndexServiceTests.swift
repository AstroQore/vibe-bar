import XCTest
import SQLite3
@testable import VibeBarCore

final class SessionIndexServiceTests: XCTestCase {
    private var home: URL!
    private var databaseURL: URL!
    private let claudeID = "11111111-2222-3333-4444-555555555555"
    private let codexID = "019c2215-0f3c-7f72-89e3-92598c209589"
    private let geminiHash = "projecthash"

    override func setUpWithError() throws {
        home = FileManager.default.temporaryDirectory
            .appendingPathComponent("VibeBarSessionIndexServiceTests-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: home, withIntermediateDirectories: true)
        databaseURL = home.appendingPathComponent("session_index.sqlite3")
    }

    override func tearDownWithError() throws {
        try? FileManager.default.removeItem(at: home)
    }

    // MARK: - Fixtures

    private func write(_ contents: String, to relativePath: String) throws -> URL {
        let url = home.appendingPathComponent(relativePath)
        try FileManager.default.createDirectory(
            at: url.deletingLastPathComponent(), withIntermediateDirectories: true
        )
        try contents.write(to: url, atomically: true, encoding: .utf8)
        return url
    }

    @discardableResult
